/**
 * Rest-timer local notification — fires an OS-level alert at rest-end so
 * the lifter still hears it with the phone locked or the app backgrounded.
 *
 * Design (see rest_timer_alarm_decision memory): ONE cue at zero, every set.
 *  - Foreground: WebAudio (`playTimerCompleteChime` in audio.ts) — instant,
 *    no permission needed, matches what the lifter sees on-screen.
 *  - Background: this module. RestTimerContext hands the cue to the OS when
 *    the page hides with a live timer (and stops its own ticking — the OS
 *    owns zero from then on). On return it cancels a still-pending
 *    notification so the foreground chime owns the cue again, or, if zero
 *    already passed while hidden, marks the period fired WITHOUT replaying
 *    the chime — the OS already rang.
 *  - Web (PWA / dev browser) no-ops every call — Capacitor's web shim uses
 *    the Notification API which is unreliable for delayed delivery while
 *    backgrounded. The in-app chime stays the only cue there.
 *
 * Permission: iOS shows its sheet once, on the first rest timer after
 * install. The OS remembers the answer; localStorage only caches a
 * `granted` so the common path skips a bridge hop. A non-granted answer is
 * NEVER trusted from cache — the lifter may have turned notifications on in
 * iOS Settings since, and the old sticky `denied` left the background path
 * off for good ("it only dings when I open the app").
 */
import { Capacitor } from '@capacitor/core';
import { LocalNotifications } from '@capacitor/local-notifications';

// Stable notification id. Re-using the same id means scheduling a new rest
// timer transparently replaces any pending one — we never get "ghost"
// notifications from a prior set that was already dismissed.
const REST_TIMER_NOTIF_ID = 1001;

// localStorage cache of a GRANTED outcome so the common path skips the
// JS↔native bridge hop. Anything else is re-checked live every time.
const PERM_CACHE_KEY = 'foundry:rest_notif_permission';

function isNative(): boolean {
  try {
    return Capacitor.isNativePlatform();
  } catch {
    return false;
  }
}

/**
 * Custom rest-complete chime — matches the in-app WebAudio two-note (G5→C6)
 * cue so foreground and background cues are perceptually identical.
 * Generated by `scripts/generate-rest-chime.py` — re-run if the chime ever
 * changes.
 *
 *   iOS:     ios/App/App/rest-complete.wav — MUST be a member of the App
 *            target (Copy Bundle Resources in project.pbxproj). `cap sync`
 *            does NOT bundle it; it only copies dist → App/public. A sound
 *            name that isn't in the bundle plays nothing — which is what
 *            every backgrounded rest did through 2.15.13.
 *   Android: android/app/src/main/res/raw/rest_complete.wav → ref by
 *            resource name (no extension; lowercase + underscores only)
 */
function customChimeSound(): string {
  try {
    if (Capacitor.getPlatform() === 'android') return 'rest_complete';
  } catch {
    /* iOS is the only shipped native platform — fall through */
  }
  // Never `undefined`: a nil sound is a SILENT notification, not the OS
  // default.
  return 'rest-complete.wav';
}

function readCachedGranted(): boolean {
  try {
    return localStorage.getItem(PERM_CACHE_KEY) === 'granted';
  } catch {
    return false;
  }
}

function writeCachedPermission(outcome: 'granted' | 'denied'): void {
  try {
    localStorage.setItem(PERM_CACHE_KEY, outcome);
  } catch {
    /* localStorage quota / private mode — silent */
  }
}

/**
 * Live permission check. True only when the OS says display is granted.
 * Re-caches `granted` so later calls short-circuit. A `denied` is written
 * for diagnostics only — it is never read as a reason to skip.
 */
async function hasLivePermission(): Promise<boolean> {
  try {
    const status = await LocalNotifications.checkPermissions();
    if (status.display === 'granted') {
      writeCachedPermission('granted');
      return true;
    }
    if (status.display === 'denied') writeCachedPermission('denied');
    return false;
  } catch {
    return false;
  }
}

/**
 * Make sure the OS will let us post a notification. Returns true if the
 * user has granted permission, false otherwise. Safe to call on every
 * rest-timer start: a cached `granted` short-circuits; anything else is a
 * live check, and the system sheet is requested only while the OS still
 * reports `prompt` (iOS shows it once, then answers from memory).
 *
 * Web platforms: always returns false (no-op path; foreground chime owns).
 */
export async function ensureNotificationPermission(): Promise<boolean> {
  if (!isNative()) return false;
  if (readCachedGranted()) return true;
  try {
    const status = await LocalNotifications.checkPermissions();
    if (status.display === 'granted') {
      writeCachedPermission('granted');
      return true;
    }
    if (status.display === 'denied') {
      writeCachedPermission('denied');
      return false;
    }
    // 'prompt' or 'prompt-with-rationale' — fire the system dialog.
    const requested = await LocalNotifications.requestPermissions();
    const granted = requested.display === 'granted';
    // Only a granted answer is worth caching. A sheet that was dismissed
    // or interrupted still reports `prompt` next time and gets re-asked.
    if (granted) writeCachedPermission('granted');
    return granted;
  } catch {
    // Plugin not registered (e.g. cap sync hasn't run) — treat as denied so
    // we don't trap callers in retry loops. Foreground chime still works.
    return false;
  }
}

/**
 * Schedule the "rest complete" OS notification to fire at `endTime` (ms
 * since epoch). Idempotent: scheduling again with the same id replaces any
 * previously-pending notification, so RestTimerContext can call this every
 * time it backgrounds without worrying about cleanup.
 *
 * Resolves TRUE when the OS accepted the notification — the caller then
 * knows the OS owns the cue at zero and must not replay it on return.
 */
export async function scheduleRestComplete(endTime: number, exName: string): Promise<boolean> {
  if (!isNative()) return false;
  if (!readCachedGranted() && !(await hasLivePermission())) return false;
  const delayMs = endTime - Date.now();
  // Anything <=0 is "the timer already ended" — nothing to schedule. Also
  // skip wildly-large futures (>1 hour) — almost certainly a bug, and we
  // don't want a stale notification firing tomorrow.
  if (delayMs <= 0 || delayMs > 60 * 60 * 1000) return false;
  try {
    await LocalNotifications.schedule({
      notifications: [
        {
          id: REST_TIMER_NOTIF_ID,
          title: 'Rest Complete',
          body: exName ? `Next set — ${exName}` : 'Next set',
          schedule: { at: new Date(endTime), allowWhileIdle: true },
          // Custom two-note chime matching the in-app WebAudio cue —
          // foreground and background ring the same.
          sound: customChimeSound(),
        },
      ],
    });
    return true;
  } catch {
    /* Schedule failed — fall through silently. Foreground chime still owns. */
    return false;
  }
}

/**
 * Cancel any PENDING rest-complete notification. Called when the lifter
 * comes back to the foreground before zero (so the in-app chime fires, not
 * the OS notification) and when they explicitly dismiss the timer.
 */
export async function cancelRestComplete(): Promise<void> {
  if (!isNative()) return;
  try {
    await LocalNotifications.cancel({
      notifications: [{ id: REST_TIMER_NOTIF_ID }],
    });
  } catch {
    /* No pending notification or plugin unavailable — silent */
  }
}

/**
 * Remove a rest-complete notification that already RANG from the
 * notification centre. Called on return to the foreground after zero
 * passed while hidden — the lifter is back, the banner has done its job.
 */
export async function clearDeliveredRestComplete(): Promise<void> {
  if (!isNative()) return;
  try {
    const delivered = await LocalNotifications.getDeliveredNotifications();
    const ours = delivered.notifications.filter((n) => n.id === REST_TIMER_NOTIF_ID);
    if (ours.length === 0) return;
    await LocalNotifications.removeDeliveredNotifications({ notifications: ours });
  } catch {
    /* plugin unavailable — silent */
  }
}
